#!/usr/bin/env python3
"""Generate the Hamming window tables as src/hamming.h.

    w[n] = 0.54 - 0.46 * cos(2*pi*n / (LEN-1))      (symmetric, MATLAB/numpy)

Quantised to Q15 (1.0 == 32767, clamped to int16) and stored as cint16 with
imag = 0, i.e. 4 bytes per point:

    struct cint16 { int16_t real; int16_t imag; };

Two tables are emitted:

    hamming_window_2048  - 2048 points, the range FFT
    hamming_window_256   -  256 points, the Doppler FFT along chirps

main.h gets a single `#include "hamming.h"`; re-running the script rewrites
hamming.h wholesale and only ever adds that one include line to main.h.

    ./gen_hamming.py                 # symmetric, write src/hamming.h
    ./gen_hamming.py --periodic      # 2*pi*n/LEN instead (DFT-even)
    ./gen_hamming.py --stdout        # print the header, change nothing
"""
import argparse
import math
import pathlib
import sys

LENGTHS = (2048, 256)
QMAX = 32767
PER_LINE = 8

INCLUDE = '#include "hamming.h"'

ROOT = pathlib.Path(__file__).resolve().parent


def find(name):
    for cand in (ROOT / "central-controller-element" / "src" / name,
                 ROOT / "src" / name):
        if cand.is_file():
            return cand
    return ROOT / "src" / name


DEFAULT_MAIN = find("main.h")
DEFAULT_OUT = (DEFAULT_MAIN.parent / "hamming.h") if DEFAULT_MAIN.is_file() else find("hamming.h")


def window(length, periodic):
    denom = length if periodic else length - 1
    return [0.54 - 0.46 * math.cos(2.0 * math.pi * n / denom) for n in range(length)]


def quantise(vals):
    return [max(-32768, min(QMAX, int(round(v * QMAX)))) for v in vals]


def emit(tables, periodic):
    kind = "periodic" if periodic else "symmetric"
    denom = "LEN" if periodic else "LEN-1"
    out = [
        "/* Generated by gen_hamming.py -- do not edit by hand. */",
        "#ifndef HAMMING_H",
        "#define HAMMING_H",
        "",
        "#include <stdint.h>",
        "",
        "/* AI Engine cint16 (adf/window/complexint.h, PL-kernel flavour):",
        " * two 16-bit halves, 4 bytes, no padding. */",
        "struct cint16 {",
        "    int16_t real;",
        "    int16_t imag;",
        "};",
        "",
    ]
    for length, q in tables:
        name = "hamming_window_%d" % length
        out += [
            "/* %d-point %s Hamming window, Q15 (1.0 == %d), imag == 0." % (length, kind, QMAX),
            " * w[n] = 0.54 - 0.46*cos(2*pi*n/(%s)); read-only, never written. */" % denom,
            "/* BEGIN %s */" % name,
        ]
        if length == 2048:
            # keep the original macro/array spelling for this table
            size = "HAMMING_LEN"
            out.append("#define HAMMING_LEN 2048")
        else:
            size = "HAMMING_LEN_%d" % length
            out.append("#define %s %d" % (size, length))
        out.append("static const struct cint16 %s[%s] = {" % (name, size))
        for i in range(0, len(q), PER_LINE):
            chunk = ", ".join("{%5d, 0}" % v for v in q[i:i + PER_LINE])
            out.append("    " + chunk + ("," if i + PER_LINE < len(q) else ""))
        out += ["};", "/* END %s */" % name, ""]
    out += ["#endif /* HAMMING_H */"]
    return "\n".join(out) + "\n"


def patch_main(text):
    """Drop any inlined table and make sure main.h includes hamming.h."""
    if INCLUDE in text:
        return text

    lines = text.split("\n")
    last = max((i for i, ln in enumerate(lines) if ln.lstrip().startswith("#include")),
               default=None)
    if last is None:
        return INCLUDE + "\n" + text
    lines.insert(last + 1, INCLUDE)
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--periodic", action="store_true",
                    help="DFT-even window (2*pi*n/LEN) instead of symmetric")
    ap.add_argument("--out", type=pathlib.Path, default=DEFAULT_OUT,
                    help="header to write (default: src/hamming.h)")
    ap.add_argument("--main", type=pathlib.Path, default=DEFAULT_MAIN,
                    help="header to add the include to (default: src/main.h)")
    ap.add_argument("--stdout", action="store_true", help="print only, do not write")
    args = ap.parse_args()

    tables = []
    for length in LENGTHS:
        w = window(length, args.periodic)
        tables.append((length, quantise(w)))

    header = emit(tables, args.periodic)

    if args.stdout:
        print(header, end="")
        return 0

    args.out.write_text(header)
    print("wrote %s" % args.out)

    if args.main.is_file():
        before = args.main.read_text()
        after = patch_main(before)
        if after != before:
            args.main.write_text(after)
            print("updated %s (%s)" % (args.main, INCLUDE))

    for length, q in tables:
        w = window(length, args.periodic)
        print("  hamming_window_%d:" % length)
        print("    points : %d" % len(q))
        print("    w[0]   : %.6f -> %d" % (w[0], q[0]))
        print("    peak   : %.6f -> %d" % (max(w), max(q)))
        print("    w[-1]  : %.6f -> %d" % (w[-1], q[-1]))
        print("    DC sum : %.3f  (quantised %d)" % (sum(w), sum(q)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
