// ---------------------------------------------------------------------------
// End-to-end testbench for the central-controller-element HLS kernel.
//
// The kernel is used unmodified.  The test drives the same three stages the
// hardware sees:
//
//   1. adc.txt --[HLS: Hamming + split]--> windowed{0,1}.txt
//      windowed{0,1}.txt --[AIE: 2048-pt range FFT]--> aie{0,1}.txt
//   2. aie{0,1}.txt --[HLS: mask walk + DRAM range cube]--> mm_range.txt
//      tb/rd_test.py builds the matching 256-pt Doppler FFT input
//      doppler{0,1}.txt from that range cube.
//   3. doppler{0,1}.txt --[HLS: Doppler window + DRAM Doppler cube]-->
//      mm_doppler.txt
//
// The ADC file is the raw 2048 x 256 range-Doppler cube generated by
// tb/rd_test.py.  Every chirp is 2048 complex samples (1024 beats of two
// samples).  The kernel is called once with num_chirps = 256, so its internal
// chirp loop, the seq_generator frame accumulation and both DRAM mappers are
// exercised.
//
// Finally tb/rd_test.py --check compares every stage against the Python model:
// the Q15 range window, the AIE range payload, the Q15 Doppler window and the
// final range-Doppler cube.
// ---------------------------------------------------------------------------

#include "../src/main.h"
#include "../src/range_part.h"

#include <cstdio>
#include <cstdlib>
#include <string>
#include <vector>

#include <sys/stat.h>
#include <sys/wait.h>
#include <unistd.h>

namespace {

struct Iq {
    int r;
    int i;
};

const unsigned kSamplesPerChirp = 2048;
const unsigned kBeatsPerChirp = kSamplesPerChirp / 2;  // 1024
const unsigned kBlocks = 128;
const unsigned kWordsPerChirp = kBlocks * 16;          // 2048
const unsigned kMaxChirps = 256;                       // one RD frame

std::string find_component_dir() {
    char buf[4096];
    if (!getcwd(buf, sizeof buf)) return std::string();
    std::string dir(buf);
    for (int i = 0; i < 12; ++i) {
        struct stat st;
        if (stat((dir + "/hls_config.cfg").c_str(), &st) == 0) return dir;
        std::string::size_type slash = dir.find_last_of('/');
        if (slash == std::string::npos || slash == 0) break;
        dir.erase(slash);
    }
    return std::string();
}

bool read_iq(const std::string &path, std::vector<Iq> &out) {
    FILE *f = std::fopen(path.c_str(), "r");
    if (!f) return false;
    out.clear();
    int r = 0, i = 0;
    while (std::fscanf(f, "%d %d", &r, &i) == 2) out.push_back(Iq{r, i});
    std::fclose(f);
    return true;
}

bool write_iq(const std::string &path, const std::vector<Iq> &v) {
    FILE *f = std::fopen(path.c_str(), "w");
    if (!f) return false;
    for (std::size_t k = 0; k < v.size(); ++k)
        std::fprintf(f, "%d %d\n", v[k].r, v[k].i);
    std::fclose(f);
    return true;
}

ap_uint<32> pack_iq(int r, int i) {
    ap_uint<32> w;
    w.range(15, 0) = (ap_uint<16>)(ap_int<16>)r;
    w.range(31, 16) = (ap_uint<16>)(ap_int<16>)i;
    return w;
}

Iq unpack_iq(ap_uint<32> w) {
    return Iq{(int)(ap_int<16>)w.range(15, 0), (int)(ap_int<16>)w.range(31, 16)};
}

void push_adc(hls::stream<pkt_adc> &in_adc0, unsigned chirps,
              const std::vector<Iq> &adc) {
    const unsigned beats = chirps * kBeatsPerChirp;
    for (unsigned b = 0; b < beats; ++b) {
        pkt_adc p;
        p.data.range(31, 0) = pack_iq(adc[2 * b].r, adc[2 * b].i);
        p.data.range(63, 32) = pack_iq(adc[2 * b + 1].r, adc[2 * b + 1].i);
        p.last = ((b + 1) % kBeatsPerChirp == 0) ? 1 : 0;
        in_adc0.write(p);
    }
}

std::vector<ap_uint<32>> load_words(const std::string &path) {
    std::vector<Iq> v;
    std::vector<ap_uint<32>> w;
    if (!read_iq(path, v)) return w;
    for (std::size_t k = 0; k < v.size(); ++k) w.push_back(pack_iq(v[k].r, v[k].i));
    return w;
}

std::vector<Iq> drain_stream(hls::stream<pkt> &s) {
    std::vector<Iq> out;
    while (!s.empty()) out.push_back(unpack_iq(s.read().data));
    return out;
}

// Stage 1: only the HLS front end.  Calling adc_forward() directly avoids
// starting the rest of the DATAFLOW region, which needs a complete 256-chirp
// frame before seq_generator can emit its ADDR_END marker.
void run_window_pass(unsigned chirps, const std::vector<Iq> &adc,
                     std::vector<Iq> &out0, std::vector<Iq> &out1) {
    hls::stream<pkt_adc> in_adc0;
    hls::stream<pkt> out00, out01;

    push_adc(in_adc0, chirps, adc);
    adc_forward(in_adc0, out00, out01, chirps);
    out0 = drain_stream(out00);
    out1 = drain_stream(out01);
}

// Stages 2 and 3 in one kernel call: the range AIE payload and the Doppler AIE
// payload are preloaded, exactly as the PL would receive them from the two
// AIE FFTs.
void run_kernel_pass(unsigned chirps, const std::vector<Iq> &adc,
                     const std::vector<ap_uint<32>> &aie0,
                     const std::vector<ap_uint<32>> &aie1,
                     const std::vector<ap_uint<32>> &dop0,
                     const std::vector<ap_uint<32>> &dop1,
                     std::vector<Iq> &dop_win0, std::vector<Iq> &dop_win1,
                     ap_uint<32> *mm) {
    hls::stream<pkt_adc> in_adc0;
    hls::stream<pkt> out_r_00, out_r_01, in_r_00, in_r_01;
    hls::stream<pkt> out_d_02, out_d_03, in_d_02, in_d_03;

    push_adc(in_adc0, chirps, adc);

    for (std::size_t k = 0; k < aie0.size(); ++k) {
        pkt p;
        p.data = aie0[k];
        p.last = 0;
        in_r_00.write(p);
    }
    for (std::size_t k = 0; k < aie1.size(); ++k) {
        pkt p;
        p.data = aie1[k];
        p.last = 0;
        in_r_01.write(p);
    }
    for (std::size_t k = 0; k < dop0.size(); ++k) {
        pkt p;
        p.data = dop0[k];
        p.last = 0;
        in_d_02.write(p);
    }
    for (std::size_t k = 0; k < dop1.size(); ++k) {
        pkt p;
        p.data = dop1[k];
        p.last = 0;
        in_d_03.write(p);
    }

    kernel(mm, in_adc0, out_r_00, out_r_01, in_r_00, in_r_01,
           out_d_02, out_d_03, in_d_02, in_d_03, chirps);

    // The range-window streams are not used in this pass.  Drain them anyway
    // so the simulation does not accumulate data.
    (void)drain_stream(out_r_00);
    (void)drain_stream(out_r_01);

    // The kernel sends the Doppler-windowed 256-point frames to the AIE here.
    dop_win0 = drain_stream(out_d_02);
    dop_win1 = drain_stream(out_d_03);
}

}  // namespace

int main() {
    const std::string comp = find_component_dir();
    if (comp.empty()) {
        std::printf("TB: cannot locate hls_config.cfg walking up from the cwd\n");
        return 1;
    }
    const std::string work = comp + "/tb/work";
    mkdir(work.c_str(), 0777);

    std::vector<Iq> adc;
    if (!read_iq(work + "/adc.txt", adc)) {
        std::printf("TB: missing %s/adc.txt -- run tb/run_test.sh\n", work.c_str());
        return 1;
    }
    if (adc.empty() || adc.size() % kSamplesPerChirp != 0) {
        std::printf("TB: ADC file has %zu samples, expected a multiple of %u\n",
                    adc.size(), kSamplesPerChirp);
        return 1;
    }
    const unsigned chirps = (unsigned)(adc.size() / kSamplesPerChirp);
    if (chirps != kMaxChirps) {
        std::printf("TB: this test needs %u chirps (one range-Doppler frame), got %u\n",
                    kMaxChirps, chirps);
        return 1;
    }

    // The range cube is at mm[0..], the Doppler cube starts kDopplerBase words
    // later.  Only sequence 0 is exercised, so the allocation covers the range
    // cube plus seq 0 of the Doppler cube.
    std::vector<ap_uint<32>> mm(kDopplerBase + kRangeBins * kChirps, 0);
    std::vector<Iq> w0, w1;

    // ---- stage 1: ADC -> Hamming window -> range AIE ----------------------
    run_window_pass(chirps, adc, w0, w1);
    if (w0.size() != chirps * kBeatsPerChirp ||
        w1.size() != chirps * kBeatsPerChirp) {
        std::printf("TB: window pass produced %zu / %zu samples, expected %u\n",
                    w0.size(), w1.size(), chirps * kBeatsPerChirp);
        return 1;
    }
    if (!write_iq(work + "/windowed0.txt", w0) ||
        !write_iq(work + "/windowed1.txt", w1)) {
        std::printf("TB: cannot write windowed output\n");
        return 1;
    }
    std::printf("TB: windowed %u chirps (%u samples) -> tb/work/windowed{0,1}.txt\n",
                chirps, chirps * kSamplesPerChirp);

    // ---- run the 2048-point range AIE, chirp by chirp ---------------------
    const std::string aie_cmd =
        "bash " + comp + "/tb/run_aie.sh " + std::to_string(chirps);
    std::printf("TB: running range AIE (%s)\n", aie_cmd.c_str());
    std::fflush(stdout);
    int aie_rc = std::system(aie_cmd.c_str());
    if (aie_rc != 0) {
        std::printf("TB: range AIE step failed (status %d)\n", aie_rc);
        return 1;
    }

    std::vector<ap_uint<32>> aie0 = load_words(work + "/aie0.txt");
    std::vector<ap_uint<32>> aie1 = load_words(work + "/aie1.txt");
    if (aie0.size() < chirps * 64 || aie1.size() < chirps * 64) {
        std::printf("TB: range AIE output too short (%zu / %zu words, need >= %u each)\n",
                    aie0.size(), aie1.size(), chirps * 64);
        return 1;
    }
    std::printf("TB: range AIE returned %zu / %zu words\n", aie0.size(), aie1.size());

    // ---- Python builds the 256-point Doppler FFT inputs -------------------
    const std::string prep_cmd =
        "python3 " + comp + "/tb/rd_test.py --prepare --chirps " +
        std::to_string(chirps);
    std::printf("TB: %s\n", prep_cmd.c_str());
    std::fflush(stdout);
    int prep_rc = std::system(prep_cmd.c_str());
    if (prep_rc != 0) {
        std::printf("TB: Doppler preparation failed (status %d)\n", prep_rc);
        return 1;
    }

    std::vector<ap_uint<32>> dop0 = load_words(work + "/doppler0.txt");
    std::vector<ap_uint<32>> dop1 = load_words(work + "/doppler1.txt");
    if (dop0.empty() || dop0.size() % 128 != 0 ||
        dop1.size() != dop0.size()) {
        std::printf("TB: Doppler input malformed (%zu / %zu words)\n",
                    dop0.size(), dop1.size());
        return 1;
    }

    // ---- stages 2+3: range consume and Doppler stage ----------------------
    std::vector<Iq> dw0, dw1;
    run_kernel_pass(chirps, adc, aie0, aie1, dop0, dop1, dw0, dw1, mm.data());

    if (!write_iq(work + "/dop_win0.txt", dw0) ||
        !write_iq(work + "/dop_win1.txt", dw1)) {
        std::printf("TB: cannot write Doppler-window output\n");
        return 1;
    }

    std::vector<Iq> mm_range;
    mm_range.reserve(chirps * kWordsPerChirp);
    for (unsigned k = 0; k < chirps * kWordsPerChirp; ++k)
        mm_range.push_back(unpack_iq(mm[k]));
    if (!write_iq(work + "/mm_range.txt", mm_range)) {
        std::printf("TB: cannot write mm_range.txt\n");
        return 1;
    }

    std::vector<Iq> mm_doppler;
    mm_doppler.reserve(kRangeBins * kChirps);
    for (unsigned r = 0; r < kRangeBins; ++r) {
        for (unsigned d = 0; d < kChirps; ++d) {
            mm_doppler.push_back(
                unpack_iq(mm[kDopplerBase + r * kChirps + d]));
        }
    }
    if (!write_iq(work + "/mm_doppler.txt", mm_doppler)) {
        std::printf("TB: cannot write mm_doppler.txt\n");
        return 1;
    }

    std::printf("TB: captured %zu range words and %zu Doppler words\n",
                mm_range.size(), mm_doppler.size());

    // ---- compare every stage against the Python model ---------------------
    const std::string check_cmd =
        "python3 " + comp + "/tb/rd_test.py --check --chirps " +
        std::to_string(chirps);
    std::printf("TB: %s\n\n", check_cmd.c_str());
    std::fflush(stdout);
    int rc = std::system(check_cmd.c_str());
    if (rc == -1) return 1;
    return WIFEXITED(rc) ? WEXITSTATUS(rc) : 1;
}
